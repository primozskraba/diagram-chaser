/** composite of a path as a Lean term: [a1,a2,a3] -> a3 ∘ₗ a2 ∘ₗ a1 */
export function compLean(D, arr) {
  if (!arr.length) return 'LinearMap.id';
  return arr.slice().reverse().map(i => D.arrows[i].lean).join(' ∘ₗ ');
}

export function compParen(D, arr) {
  return arr.length > 1 ? `(${compLean(D, arr)})` : compLean(D, arr);
}

/** apply a path (array of arrow indices) to a Lean term */
export function applyLean(D, arr, term) {
  let t = term;
  for (const i of arr) t = `${D.arrows[i].lean} ${atomic(t) ? t : `(${t})`}`;
  return t;
}

function atomic(t) { return /^[^\s()]+$/.test(t) || /^\(.*\)$/.test(t) && balanced(t.slice(1, -1)); }
function balanced(s) {
  let d = 0;
  for (const ch of s) { if (ch === '(') d++; else if (ch === ')') { d--; if (d < 0) return false; } }
  return d === 0;
}

export function applyHuman(D, arr, term) {
  let t = term;
  for (const i of arr) { const n = D.arrows[i].name; t = `${n.includes('∘') ? `(${n})` : n}(${t})`; }
  return t;
}

function coefLean(c) {
  if (!c.isInt()) throw new Error('non-integral certificate (needs division by an integer)');
  return c.n;
}

/** Lean expression for a vector over atoms */
export function vecLean(chase, vec) {
  const D = chase.D;
  const items = [...vec].sort((a, b) => chase.atoms.get(a[0]).idx - chase.atoms.get(b[0]).idx);
  if (!items.length) return '0';
  let out = '';
  items.forEach(([k, c], n) => {
    const a = chase.atoms.get(k);
    const term = applyLean(D, parseKey(a.path), chase.vars[a.varId].name);
    const z = coefLean(c);
    const mag = z < 0n ? -z : z;
    const body = mag === 1n ? term : `(${mag} : ℤ) • ${term}`;
    if (n === 0) out = z < 0n ? `-${body}` : body;
    else out += z < 0n ? ` - ${body}` : ` + ${body}`;
  });
  return out;
}

export function vecHuman(chase, vec) {
  const D = chase.D;
  const items = [...vec].sort((a, b) => chase.atoms.get(a[0]).idx - chase.atoms.get(b[0]).idx);
  if (!items.length) return '0';
  let out = '';
  items.forEach(([k, c], n) => {
    const a = chase.atoms.get(k);
    const term = applyHuman(D, parseKey(a.path), chase.vars[a.varId].name);
    const neg = c.n < 0n;
    const mag = neg ? c.neg() : c;
    const body = mag.isInt() && mag.n === 1n ? term : `${mag}·${term}`;
    if (n === 0) out = neg ? `−${body}` : body;
    else out += neg ? ` − ${body}` : ` + ${body}`;
  });
  return out;
}

export const paren = (s) => (atomic(s) ? s : `(${s})`);

/**
 * Lines proving a goal `... = 0` (already the current goal) from a certificate.
 * ctx: {chase, factRef(factId) -> Lean term, simp: string, fresh}
 */
export function deriveTactic(ctx, cert) {
  const { chase } = ctx;
  const D = chase.D;
  const entries = certEntries(cert).filter(e => !e.coef.isZero());
  const lines = [];
  const names = [];
  entries.forEach((e, n) => {
    const nm = `${ctx.ePrefix || 'e'}${sub(n + 1)}`;
    names.push(nm);
    let term = ctx.factRef(e.fact);
    for (const i of parseKey(e.path)) term = `DC.push ${D.arrows[i].lean} ${paren(term)}`;
    lines.push(`have ${nm} := ${term}`);
  });
  const at = names.length ? ` at ${names.join(' ')} ⊢` : '';
  lines.push(`try simp only [${ctx.simp}]${at}`);
  if (!entries.length) {
    lines.push('all_goals abel');
  } else {
    const combo = entries.map((e, n) => {
      const z = coefLean(e.coef);
      const mag = z < 0n ? -z : z;
      const body = mag === 1n ? names[n] : `(${mag} : ℤ) • ${names[n]}`;
      if (n === 0) return z < 0n ? `-${body}` : body;
      return z < 0n ? ` - ${body}` : ` + ${body}`;
    }).join('');
    lines.push(`all_goals linear_combination (norm := abel) ${combo}`);
  }
  return lines;
}

const SUB = '₀₁₂₃₄₅₆₇₈₉';
export const sub = (n) => String(n).split('').map(d => SUB[+d]).join('');

/** wrap tactic lines as a parenthesised `by` term, indented */
export function byTerm(lines, indent) {
  const pad = ' '.repeat(indent);
  return `(by\n${lines.map(l => pad + l).join('\n')})`;
}

export const flat = (lines) => lines.flatMap(l => l.split('\n'));

export function indentLines(lines, n) {
  const pad = ' '.repeat(n);
  return flat(lines).map(l => (l.length ? pad + l : l));
}

/**
 * Prune chase steps: which steps are needed for the final certificate(s) and
 * vectors (witness etc.). Returns a sorted array of step indices.
 */
export function neededSteps(chase, certs, vecs) {
  const need = new Set();
  const queue = [];
  const addFact = (fid) => {
    const f = chase.facts[fid];
    if (f.step === undefined || f.step < 0) return;
    if (!need.has(f.step)) { need.add(f.step); queue.push(f.step); }
  };
  const addVec = (v) => {
    for (const vid of varsOfVec(chase, v)) {
      const st = chase.vars[vid].step;
      if (st !== undefined && st >= 0 && !need.has(st)) { need.add(st); queue.push(st); }
    }
  };
  for (const c of certs) for (const e of certEntries(c)) addFact(e.fact);
  for (const v of vecs) addVec(v);
  while (queue.length) {
    const s = chase.steps[queue.pop()];
    for (const c of [s.cert, s.cert1, s.cert2].filter(Boolean)) for (const e of certEntries(c)) addFact(e.fact);
    for (const v of [s.v, s.u, s.w].filter(Boolean)) addVec(v);
  }
  return [...need].sort((a, b) => a - b);
}
